"""Report assembly. Deterministic: no timestamps, no absolute paths, no
randomness -> the same input tree yields a byte-identical report."""
from __future__ import annotations

import json
import os

from . import authority as authmod
from . import checks
from .defaults import DEFAULTS
from .model import (DIMENSION_ORDER, REPORT_VERSION, TOOL_LABEL, TOOL_ORDER,
                    TOOL_VERSION, Dimension, Severity, Tool)
from .parsers import parse_repo


def analyze(root: str, name: str | None = None) -> dict:
    root = os.path.abspath(root)
    parsed = parse_repo(root)
    configs = parsed["configs"]
    ctx = {
        "root": root,
        "version_controlled": parsed["version_controlled"],
        "secret_paths": parsed["secret_paths"],
    }
    authority = authmod.compute(configs, ctx)
    findings = checks.run_all(configs, authority, ctx)
    not_judgeable = checks.collect_not_judgeable(configs, authority)

    tools_out = {}
    for t in TOOL_ORDER:
        cfg = configs[t]
        tools_out[t.value] = {
            "label": TOOL_LABEL[t],
            "surfaces": [s.to_dict() for s in cfg.surfaces],
            "authority": [authority[t][dim].to_dict() for dim in DIMENSION_ORDER],
            "parse_problems": [p.to_dict() for p in cfg.problems],
            "instruction_files": list(cfg.instructions),
        }

    by_check = {}
    by_sev = {}
    for f in findings:
        by_check[f.check] = by_check.get(f.check, 0) + 1
        by_sev[f.severity.value] = by_sev.get(f.severity.value, 0) + 1

    return {
        "report_version": REPORT_VERSION,
        "tool": "repogrant",
        "tool_version": TOOL_VERSION,
        "target": name if name is not None else os.path.basename(root),
        "repo_facts": {
            "version_controlled": parsed["version_controlled"],
            "secret_paths": parsed["secret_paths"],
        },
        "tools": tools_out,
        "findings": [f.to_dict() for f in findings],
        "not_judgeable": not_judgeable,
        "summary": {
            "total_findings": len(findings),
            "findings_by_check": by_check,
            "findings_by_severity": by_sev,
            "not_judgeable_count": len(not_judgeable),
        },
    }


def to_json(report: dict) -> str:
    """Canonical, byte-stable serialisation."""
    return json.dumps(report, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def defaults_matrix() -> dict:
    """Part B: the documented defaults matrix as data (one source of truth)."""
    rows = {}
    for t in TOOL_ORDER:
        cells = {}
        for dim in DIMENSION_ORDER:
            dc = DEFAULTS[t][dim]
            cell = {
                "judgeable": dc["judgeable"],
                "value": dc["value"] if dc["judgeable"] else "not-judgeable",
                "consent_required": dc["consent_required"],
            }
            if dc["judgeable"]:
                cell["quote"] = dc["quote"]
                cell["url"] = dc["url"]
                if dc["note"]:
                    cell["note"] = dc["note"]
                if dc["dual"]:
                    cell["dual"] = dc["dual"]
            else:
                cell["reason"] = dc["reason"]
            cells[dim.value] = cell
        rows[t.value] = {"label": TOOL_LABEL[t], "dimensions": cells}
    return {
        "report_version": REPORT_VERSION,
        "tool_version": TOOL_VERSION,
        "scenario": "A freshly cloned repository with NO agent config of any kind; "
                    "a developer opens it in each tool with that tool's out-of-box settings.",
        "tools": rows,
    }


def render_defaults_md(matrix: dict) -> str:
    """Render the defaults matrix as a pinned, citable audit document."""
    lines = []
    lines.append("# RepoGrant — Part B: tool defaults matrix")
    lines.append("")
    lines.append(f"*Generated by repogrant {matrix['tool_version']} (report schema "
                 f"{matrix['report_version']}). Deterministic; regenerate with "
                 f"`repogrant defaults --md`.*")
    lines.append("")
    lines.append(f"**Scenario.** {matrix['scenario']}")
    lines.append("")
    lines.append("Each cell is what the tool grants **with no repo config**, on each authority "
                 "dimension, traceable to a verbatim primary-source quote. `not-judgeable` cells are "
                 "undetermined *by the documented record* — recorded, never guessed.")
    lines.append("")
    for dim in DIMENSION_ORDER:
        lines.append(f"## {dim.value}")
        lines.append("")
        lines.append("| Tool | Default | Consent | Source quote |")
        lines.append("|------|---------|---------|--------------|")
        for t in TOOL_ORDER:
            cell = matrix["tools"][t.value]["dimensions"][dim.value]
            consent = ("per-call" if cell["consent_required"] is True
                       else "none" if cell["consent_required"] is False else "—")
            if cell["judgeable"]:
                quote = cell.get("quote", "").replace("|", "\\|")
                src = f'"{quote}" — <{cell.get("url","")}>'
                val = cell["value"]
                if cell.get("dual"):
                    branches = "; ".join(f'{b["label"]}: {b["value"]}' for b in cell["dual"])
                    val = f'{val}  _(branches — {branches})_'
            else:
                src = f'_not-judgeable: {cell["reason"]}_'.replace("|", "\\|")
                val = "not-judgeable"
            lines.append(f"| {TOOL_LABEL[t]} | {val} | {consent} | {src} |")
        lines.append("")
    lines.append("---")
    lines.append("")
    lines.append("**Reading the trap (R4).** The cells that are *not* empty for a silent repo are the "
                 "defaults trap: a cloned repo with nothing configured still grants these. Notably, Gemini "
                 "honors a repo's `.gemini/` config and `.env` by default (Folder Trust off), and Codex in a "
                 "version-controlled folder defaults to `workspace-write` rather than read-only.")
    lines.append("")
    return "\n".join(lines)
